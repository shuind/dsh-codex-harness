import { describe, expect, it, vi } from 'vitest'
import type { Agent } from '@deepseek-ai/dsh-agent'
import ToolPolicy, { apply, Config } from '../../src/entries/tool-policy.ts'
import { capability, fsNames, harness } from './policy-harness.ts'

describe('opt-in Host tool policy', () => {
  it('defaults to no rules and never changes existing Agents', async () => {
    const h = await harness()
    const source = h.preset('standard')
    const existing = h.prepare('standard')
    await existing.publish()
    const plugin = await h.mount()
    const created = h.prepare('standard')
    await created.publish()
    expect(Config({}).get()).toEqual({ rules: [] })
    const parsed = Config({ rules: [{ preset: 'target' }, { preset: 'empty', allow: [] }] }).get()!
    expect(parsed.rules[0]!.allow).toBeUndefined()
    expect(parsed.rules[0]!.deny).toBeUndefined()
    expect(parsed.rules[0]!.tools).toBeUndefined()
    expect(Config({ rules: [{ preset: 'target', tools: [] }] }).get()!.rules[0]!.tools).toEqual([])
    expect(parsed.rules[0]!.replaceShell).toBe(true)
    expect(parsed.rules[0]!.replacePlan).toBe(true)
    expect(parsed.rules[1]!.allow).toEqual([])
    for (const agent of [existing.agent, created.agent]) {
      expect(h.names(agent)).toEqual(Object.keys(source.definitions))
    }
    await plugin.dispose()
  })

  it('replaces new target Agents only, retaining file definitions and Persona by reference', async () => {
    const h = await harness()
    const source = h.preset('standard')
    const other = h.preset('other')
    const existing = h.prepare('standard')
    await existing.publish()
    await h.mount({ rules: [{ preset: 'standard' }] })
    const target = h.prepare('standard')
    const sibling = h.prepare('other')
    await target.publish()
    await sibling.publish()
    expect(h.names(target.agent)).not.toContain('pwsh')
    expect(h.names(target.agent)).not.toContain('todo_write')
    expect(h.names(target.agent)).toEqual(expect.arrayContaining(['exec_command', 'write_stdin', 'update_plan']))
    for (const name of fsNames) expect(h.ctx.tools.get(name, target.agent)).toBe(source.definitions[name])
    for (const name of Object.keys(other.definitions)) expect(h.ctx.tools.get(name, sibling.agent)).toBe(other.definitions[name])
    expect(h.names(existing.agent)).toEqual(Object.keys(source.definitions))
    expect(h.ctx.tools.get('pwsh', source.key)).toBe(source.definitions.pwsh)
    expect(h.ctx.tools.get('exec_command')).toBeUndefined()
    const assembly = await h.ctx.systemPrompt.assemble({ scope: target.agent, agent: target.agent })
    const baseline = await h.ctx.systemPrompt.assemble({ scope: existing.agent, agent: existing.agent })
    expect(assembly.sections.filter(section => section.name !== 'codex:tool-policy')).toEqual(baseline.sections)
    expect(assembly.contexts).toEqual(baseline.contexts)
    expect(assembly.variables).toEqual(baseline.variables)
    const guidance = assembly.sections.find(section => section.name === 'codex:tool-policy')!.text
    expect(guidance).toContain('exec_command and write_stdin')
    expect(guidance).toContain('exit_code')
    expect(guidance).toContain('at most one plan item may be in_progress')
    expect(assembly.tools.map(tool => tool.name)).toEqual(expect.arrayContaining(['exec_command', 'write_stdin', 'update_plan', 'apply_patch']))
  })

  it.each(['bash', 'pwsh'])('replaces the audited %s source without adding a patch tool', async source => {
    const h = await harness()
    h.preset('standard', [source, 'read'])
    await h.mount({ rules: [{ preset: 'standard' }] })
    const candidate = h.prepare('standard')
    await candidate.publish()
    expect(h.names(candidate.agent)).toEqual(['read', 'exec_command', 'write_stdin'])
    expect(h.ctx.tools.get('apply_patch', candidate.agent)).toBeUndefined()
  })

  it('applies masks before replacement and treats an empty allowlist as deny-all', async () => {
    const h = await harness()
    const source = h.preset('read-only')
    h.preset('empty')
    await h.mount({ rules: [
      { preset: 'read-only', allow: ['read', 'glob'], deny: ['glob'] },
      { preset: 'empty', allow: [] },
    ] })
    const readOnly = h.prepare('read-only')
    const empty = h.prepare('empty')
    await readOnly.publish()
    await empty.publish()
    expect(h.names(readOnly.agent)).toEqual(['read'])
    expect(h.ctx.tools.get('read', readOnly.agent)).toBe(source.definitions.read)
    expect(h.names(empty.agent)).toEqual([])
    for (const candidate of [readOnly, empty]) {
      const assembly = await h.ctx.systemPrompt.assemble({ scope: candidate.agent, agent: candidate.agent })
      expect(assembly.sections.some(section => section.name === 'codex:tool-policy')).toBe(false)
    }
  })

  it('supports selective replacement and never grants abilities whose sources are absent', async () => {
    const h = await harness()
    h.preset('shell-only')
    h.preset('plan-only')
    h.preset('absent', ['read', 'other_tool'])
    await h.mount({ rules: [
      { preset: 'shell-only', replacePlan: false, deny: ['other_tool'] },
      { preset: 'plan-only', replaceShell: false },
      { preset: 'absent' },
    ] })
    const shell = h.prepare('shell-only')
    const plan = h.prepare('plan-only')
    const absent = h.prepare('absent')
    await shell.publish()
    await plan.publish()
    await absent.publish()
    expect(h.names(shell.agent)).toEqual(expect.arrayContaining(['exec_command', 'write_stdin', 'todo_write']))
    expect(h.names(shell.agent)).not.toContain('other_tool')
    expect(h.names(shell.agent)).not.toContain('update_plan')
    expect(h.names(plan.agent)).toEqual(expect.arrayContaining(['pwsh', 'update_plan']))
    expect(h.names(plan.agent)).not.toContain('exec_command')
    expect(h.names(absent.agent)).toEqual(['read', 'other_tool'])
  })

  it('replaces edit and/or write with one shared apply_patch registration and prompts accordingly', async () => {
    const h = await harness()
    h.preset('both', ['read', 'edit', 'write'])
    h.preset('legacy-off', ['read', 'edit', 'write'])
    h.preset('legacy-on', ['read', 'edit', 'write'])
    await h.mount({ rules: [
      { preset: 'both', replaceShell: false, replacePlan: false, tools: [
        { name: 'edit', action: 'codex-patch' },
        { name: 'write', action: 'codex-patch' },
      ] },
      { preset: 'legacy-off' },
      { preset: 'legacy-on', replacePatch: true },
    ] })
    const both = h.prepare('both')
    const off = h.prepare('legacy-off')
    const on = h.prepare('legacy-on')
    await both.publish(); await off.publish(); await on.publish()
    expect(h.names(both.agent)).toEqual(['read', 'apply_patch'])
    expect(h.names(off.agent)).toEqual(['read', 'edit', 'write'])
    expect(h.names(on.agent)).toEqual(['read', 'apply_patch'])
    expect((await h.dispatch(both.agent, 'apply_patch', {
      input: '*** Begin Patch\n*** Add File: via-policy.txt\n+hi\n*** End Patch',
    })).results[0]!.result.isError).toBe(false)
    expect(h.patchWrites).toHaveBeenCalledOnce()
    const assembly = await h.ctx.systemPrompt.assemble({ scope: both.agent, agent: both.agent })
    expect(assembly.sections.find(s => s.name === 'codex:tool-policy')?.text).toContain('edit/write is replaced by apply_patch')
  })

  it.each(['bash', 'pwsh', 'todo_write'])('refuses conditional %s and rolls back every mask', async sourceName => {
    const h = await harness()
    const source = h.preset('standard', [sourceName, 'read', 'other_tool'], { [sourceName]: () => true })
    await h.mount({ rules: [{ preset: 'standard', deny: ['other_tool'] }] })
    const candidate = h.prepare('standard')
    await expect(candidate.publish()).rejects.toThrow(/conditional source tool/)
    expect(h.names(candidate.agent)).toEqual(Object.keys(source.definitions))
    expect(h.ctx.tools.get(sourceName, candidate.agent)).toBe(source.definitions[sourceName])
    expect(h.ctx.tools.get('exec_command', candidate.agent)).toBeUndefined()
    expect(h.ctx.tools.get('update_plan', candidate.agent)).toBeUndefined()
  })

  it.each(['exec_command', 'write_stdin', 'update_plan'])('refuses a pre-existing %s instead of shadowing it', async collision => {
    const h = await harness()
    const source = h.preset('standard', ['pwsh', 'todo_write', collision, 'read', 'other_tool'])
    await h.mount({ rules: [{ preset: 'standard', deny: ['other_tool'] }] })
    const candidate = h.prepare('standard')
    await expect(candidate.publish()).rejects.toThrow(/already exists; refusing to shadow/)
    expect(h.names(candidate.agent)).toEqual(Object.keys(source.definitions))
    expect(h.ctx.tools.get(collision, candidate.agent)).toBe(source.definitions[collision])
  })

  it.each(['allow', 'deny'] as const)('refuses unknown and Agent-local %s names atomically', async mask => {
    const h = await harness()
    const source = h.preset('standard')
    h.preset('local')
    await h.mount({ rules: [
      { preset: 'standard', [mask]: ['does_not_exist'] },
      { preset: 'local', [mask]: ['local_tool'] },
    ] })
    const unknown = h.prepare('standard')
    await expect(unknown.publish()).rejects.toThrow(/unknown global tool/)
    expect(h.names(unknown.agent)).toEqual(Object.keys(source.definitions))
    const own = capability('local_tool')
    const local = h.prepare('local', [own])
    await expect(local.publish()).rejects.toThrow(/Agent-local tool/)
    expect(h.ctx.tools.get('local_tool', local.agent)).toBe(own)
    expect(h.names(local.agent)).toContain('pwsh')
    expect(h.names(local.agent)).not.toContain('exec_command')
  })

  it('rolls back restrictions when an identical Agent-owned source cannot be hidden', async () => {
    const h = await harness()
    const source = h.preset('standard')
    await h.mount({ rules: [{ preset: 'standard', deny: ['other_tool'] }] })
    // Even reference identity cannot prove ownership: restrict must hide it.
    const candidate = h.prepare('standard', [source.definitions.pwsh!])
    await expect(candidate.publish()).rejects.toThrow(/cannot hide Agent-local source/)
    expect(h.names(candidate.agent)).toEqual(Object.keys(source.definitions))
    expect(h.ctx.tools.get('other_tool', candidate.agent)).toBe(source.definitions.other_tool)
    expect(h.ctx.tools.get('exec_command', candidate.agent)).toBeUndefined()
  })

  it('synchronously reconciles blank new Agents and ignores old Agents even after selection', async () => {
    const h = await harness()
    h.preset('target')
    const other = h.preset('other')
    const existing = h.prepare('other')
    await existing.publish()
    await h.mount({ rules: [{ preset: 'target' }] })
    const created = h.prepare('target')
    await created.publish()
    const initialExec = h.ctx.tools.get('exec_command', created.agent)
    created.switchPreset('other')
    expect(h.ctx.tools.get('exec_command', created.agent)).toBeUndefined()
    expect(h.ctx.tools.get('pwsh', created.agent)).toBe(other.definitions.pwsh)
    created.switchPreset('target')
    expect(h.ctx.tools.get('exec_command', created.agent)).toBeDefined()
    expect(h.ctx.tools.get('exec_command', created.agent)).not.toBe(initialExec)
    created.switchPreset('target')
    expect(h.names(created.agent).filter(name => name === 'exec_command')).toHaveLength(1)
    existing.switchPreset('target')
    expect(h.ctx.tools.get('exec_command', existing.agent)).toBeUndefined()
    expect(h.ctx.tools.get('pwsh', existing.agent)).toBeDefined()
  })

  it('prefers the live composition over the creation-header preset', async () => {
    const h = await harness()
    h.preset('target')
    h.preset('other')
    await h.mount({ rules: [{ preset: 'target' }] })
    const candidate = h.prepare('target')
    candidate.switchPreset('other')
    await candidate.publish()
    expect(candidate.agent.session.header.agentPreset).toBe('target')
    expect(h.ctx.tools.get('exec_command', candidate.agent)).toBeUndefined()
    expect(h.ctx.tools.get('pwsh', candidate.agent)).toBeDefined()
  })

  it('does not reconcile active or nonblank Agents, and uses no idle polling', async () => {
    const h = await harness()
    h.preset('target')
    h.preset('other')
    await h.mount({ rules: [{ preset: 'target' }] })
    const running = h.prepare('target')
    await running.publish()
    const original = h.ctx.tools.get('exec_command', running.agent)
    running.setStatus('running')
    running.switchPreset('other')
    expect(h.ctx.tools.get('exec_command', running.agent)).toBe(original)
    running.setStatus('idle')
    h.ctx.emit('agent/status', { agent: running.agent, status: 'idle' })
    expect(h.ctx.tools.get('exec_command', running.agent)).toBe(original)
    const nonblank = h.prepare('target')
    await nonblank.publish()
    nonblank.agent.session.append('turn/start', { turn: 1 })
    nonblank.agent.session.append('turn/end', { turn: 1, reason: { kind: 'completed' } })
    const nonblankExec = h.ctx.tools.get('exec_command', nonblank.agent)
    nonblank.switchPreset('other')
    expect(h.ctx.tools.get('exec_command', nonblank.agent)).toBe(nonblankExec)
  })

  it('leaves the new baseline intact when a blank-switch replacement is refused', async () => {
    const h = await harness()
    h.preset('target')
    const invalid = h.preset('conditional', ['pwsh', 'read'], { pwsh: () => false })
    await h.mount({ rules: [{ preset: 'target' }, { preset: 'conditional' }] })
    const warnings = vi.spyOn(h.ctx.logger, 'warn').mockImplementation(() => {})
    const candidate = h.prepare('target')
    await candidate.publish()
    candidate.switchPreset('conditional')
    expect(h.ctx.tools.get('exec_command', candidate.agent)).toBeUndefined()
    expect(h.ctx.tools.get('pwsh', candidate.agent)).toBe(invalid.definitions.pwsh)
    expect(warnings).toHaveBeenCalledWith(expect.stringContaining('conditional source tool'))
  })

  it('unwinds on either Agent disposal or Host-plugin unload without touching another preset', async () => {
    const h = await harness()
    const source = h.preset('target')
    const other = h.preset('other')
    const plugin = await h.mount({ rules: [{ preset: 'target' }] })
    const first = h.prepare('target')
    const second = h.prepare('target')
    const sibling = h.prepare('other')
    await first.publish()
    await second.publish()
    await sibling.publish()
    await first.scoped.dispose()
    expect(h.ctx.agents.get(first.agent.id)).toBeUndefined()
    expect(h.ctx.tools.get('exec_command', first.agent)).toBeUndefined()
    expect(h.ctx.tools.get('pwsh', first.agent)).toBe(source.definitions.pwsh)
    expect(h.ctx.tools.get('exec_command', second.agent)).toBeDefined()
    await plugin.dispose()
    await plugin.dispose()
    expect(h.ctx.tools.get('exec_command', second.agent)).toBeUndefined()
    expect(h.ctx.tools.get('pwsh', second.agent)).toBe(source.definitions.pwsh)
    for (const name of fsNames) expect(h.ctx.tools.get(name, second.agent)).toBe(source.definitions[name])
    const restored = await h.ctx.systemPrompt.assemble({ scope: second.agent, agent: second.agent })
    const untouched = await h.ctx.systemPrompt.assemble({ scope: sibling.agent, agent: sibling.agent })
    expect(restored.sections.some(section => section.name === 'codex:tool-policy')).toBe(false)
    expect(restored.sections).toEqual(untouched.sections)
    expect(restored.contexts).toEqual(untouched.contexts)
    expect(restored.variables).toEqual(untouched.variables)
    expect(h.ctx.tools.get('pwsh', sibling.agent)).toBe(other.definitions.pwsh)
    const later = h.prepare('target')
    await later.publish()
    expect(h.ctx.tools.get('exec_command', later.agent)).toBeUndefined()
  })

  it('retains Native argument errors, denial, nonzero exits, and durable call/result correlation', async () => {
    const h = await harness()
    h.preset('target')
    await h.mount({ rules: [{ preset: 'target' }] })
    const candidate = h.prepare('target')
    await candidate.publish()
    const nonzero = await h.dispatch(candidate.agent, 'exec_command', { cmd: 'nonzero' })
    expect(nonzero.results[0]!.result).toMatchObject({ isError: false, value: { exit_code: 7 } })
    const failure = await h.dispatch(candidate.agent, 'exec_command', { cmd: 'infrastructure-failure' })
    expect(failure.results[0]!.result).toMatchObject({ isError: true, error: { info: { code: 'TEST_SHELL_FAILED' } } })
    const invalid = await h.dispatch(candidate.agent, 'exec_command', { cmd: 123 })
    expect(invalid.results[0]!.result).toMatchObject({ isError: true, error: { info: { code: 'INVALID_ARGS' } } })
    const stopGuard = candidate.agent.ctx.get('tools')!.guard(exec => exec.name === 'update_plan' ? 'test denial' : undefined)
    const denial = await h.dispatch(candidate.agent, 'update_plan', { plan: [] })
    expect(denial.results[0]!.result).toMatchObject({ isError: true, error: { message: 'test denial' } })
    stopGuard()
    const events = candidate.agent.session.snapshotEvents()
    const calls = events.filter(event => event.type === 'tool/call')
    const results = events.filter(event => event.type === 'tool/result')
    expect(calls).toHaveLength(4)
    expect(results).toHaveLength(4)
    expect(results.map(event => event.data.message.toolCallId)).toEqual(calls.map(event => event.data.callId))
    expect(results.map(event => event.data.message.isError)).toEqual([false, true, true, true])
    expect(h.executeShell).toHaveBeenCalledTimes(2)
  })

  it('saves volatile rules for future Agents without restarting or changing earlier snapshots', async () => {
    const h = await harness()
    const target = h.preset('target')
    const other = h.preset('other')
    const plugin = await h.mountWithLoader({ rules: [{ preset: 'target', replacePlan: false }] })
    const first = h.prepare('target')
    await first.publish()
    const initialExec = h.ctx.tools.get('exec_command', first.agent)
    expect(initialExec).toBeDefined()
    expect(h.ctx.tools.get('todo_write', first.agent)).toBe(target.definitions.todo_write)
    await plugin.update({ rules: [{ preset: 'other', replaceShell: false }] })
    // A root-volatile update must not trigger Host cleanup/restart.
    expect(h.ctx.tools.get('exec_command', first.agent)).toBe(initialExec)
    expect(h.ctx.tools.get('update_plan', first.agent)).toBeUndefined()
    const laterTarget = h.prepare('target')
    const laterOther = h.prepare('other')
    await laterTarget.publish()
    await laterOther.publish()
    expect(h.ctx.tools.get('exec_command', laterTarget.agent)).toBeUndefined()
    expect(h.ctx.tools.get('pwsh', laterTarget.agent)).toBe(target.definitions.pwsh)
    expect(h.ctx.tools.get('update_plan', laterOther.agent)).toBeDefined()
    expect(h.ctx.tools.get('pwsh', laterOther.agent)).toBe(other.definitions.pwsh)
    // The old Agent's blank-switch behavior also uses its creation-time rules.
    first.switchPreset('other')
    expect(h.ctx.tools.get('exec_command', first.agent)).toBeUndefined()
    expect(h.ctx.tools.get('update_plan', first.agent)).toBeUndefined()
    first.switchPreset('target')
    expect(h.ctx.tools.get('exec_command', first.agent)).toBeDefined()
    expect(h.ctx.tools.get('update_plan', first.agent)).toBeUndefined()
    expect(h.ctx.tools.get('todo_write', first.agent)).toBe(target.definitions.todo_write)
  })

  it('does not retrofit Agents created before the first rule is saved', async () => {
    const h = await harness()
    h.preset('target')
    h.preset('other')
    const plugin = await h.mountWithLoader()
    const first = h.prepare('other')
    await first.publish()
    await plugin.update({ rules: [{ preset: 'target' }] })
    first.switchPreset('target')
    expect(h.ctx.tools.get('exec_command', first.agent)).toBeUndefined()
    const later = h.prepare('target')
    await later.publish()
    expect(h.ctx.tools.get('exec_command', later.agent)).toBeDefined()
  })

  it('rejects duplicate rules rather than composing ambiguous masks', async () => {
    const h = await harness()
    expect(() => apply(h.ctx, { rules: [{ preset: 'target' }, { preset: 'target' }] })).toThrow(/duplicate preset rule/)
  })
})

